// Old film and episode URLs that should 301 to their current page, so links and search results
// keep working when a slug changes (a remake gets "-2016" appended, a title gets corrected).
// The map lives in data/redirects.json; build-data adds to it and writes public/_redirects.
import type { Episode, Film } from '../../src/lib/types.ts';

export type Redirects = { films: Record<string, string>; episodes: Record<string, string> };

// Loose title key: "The Haunting in Connecticut" and "A Haunting in Connecticut" agree.
const loose = (s: string) =>
	s
		.toLowerCase()
		.replace(/^(the|a|an) /, '')
		.replace(/[^a-z0-9]+/g, '');
// Leftovers from timestamped chapter lists: "05-review-nosferatu", "30-spoiler-discussion-scream".
const JUNK_PREFIX = /^\d+-(review|retro-review|other-stuff-we-watched|spoiler-discussion)-/;

export function filmMatcher(current: Film[]) {
	const slugs = new Set(current.map((f) => f.slug));
	const byTmdb = new Map(current.filter((f) => f.tmdb).map((f) => [`${f.tmdb!.type}:${f.tmdb!.id}`, f.slug]));
	const byTitle = new Map(current.map((f) => [`${f.title.toLowerCase()}|${f.year ?? ''}`, f.slug]));
	// Only unambiguous loose matches count.
	const byLoose = new Map<string, string | null>();
	for (const f of current) {
		const k = loose(f.title);
		byLoose.set(k, byLoose.has(k) ? null : f.slug);
	}
	const match = (old: Pick<Film, 'slug' | 'title' | 'year' | 'tmdb'>): string | null => {
		if (old.tmdb) {
			const hit = byTmdb.get(`${old.tmdb.type}:${old.tmdb.id}`);
			if (hit) return hit;
		}
		const exact = byTitle.get(`${old.title.toLowerCase()}|${old.year ?? ''}`);
		if (exact) return exact;
		const stripped = old.slug.replace(JUNK_PREFIX, '');
		if (stripped !== old.slug && slugs.has(stripped)) return stripped;
		const title = stripped === old.slug ? old.title : stripped.replace(/-/g, ' ');
		const fuzzy = byLoose.get(loose(title));
		if (fuzzy) return fuzzy;
		// "13 Hours" became "13 Hours: The Secret Soldiers of Benghazi".
		const longer = current.filter((f) => f.title.toLowerCase().startsWith(title.toLowerCase() + ':'));
		return longer.length === 1 ? longer[0].slug : null;
	};
	return (old: Pick<Film, 'slug' | 'title' | 'year' | 'tmdb'>): string | null => {
		// A note or a bundle fixed since: "Pacific Rim (with D-BOX)", "FlashForward / Community".
		const trimmed = old.title.replace(/\s*\([^)]*\)$/, '').split(/\s+[/+]\s+/)[0];
		return match(old) ?? (trimmed !== old.title ? match({ slug: '', title: trimmed, year: old.year, tmdb: null }) : null);
	};
}

// An episode is the same episode if it has the same audio link or number and date.
export function episodeMatcher(current: Episode[]) {
	const keys = (e: Episode) =>
		[e.links.libsyn, e.links.patreon, e.links.bandcamp, e.number ? `${e.kind}|${e.number}|${e.date}` : null].filter(Boolean) as string[];
	const index = new Map<string, string>();
	for (const e of current) for (const k of keys(e)) if (!index.has(k)) index.set(k, e.id);
	return (old: Episode) => keys(old).map((k) => index.get(k)).find(Boolean) ?? null;
}

// Adds redirects for pages that are gone, then repoints any chain (a → b, b → c) at the final page
// and drops entries whose old URL is a live page again.
export function updateRedirects(
	redirects: Redirects,
	previous: { films: Film[]; episodes: Episode[] },
	current: { films: Film[]; episodes: Episode[] },
) {
	const liveFilms = new Set(current.films.map((f) => f.slug));
	const liveEpisodes = new Set(current.episodes.map((e) => e.id));
	const matchFilm = filmMatcher(current.films);
	const matchEpisode = episodeMatcher(current.episodes);
	for (const f of previous.films)
		if (!liveFilms.has(f.slug) && !redirects.films[f.slug]) {
			const to = matchFilm(f);
			if (to) redirects.films[f.slug] = to;
		}
	for (const e of previous.episodes)
		if (!liveEpisodes.has(e.id) && !redirects.episodes[e.id]) {
			const to = matchEpisode(e);
			if (to) redirects.episodes[e.id] = to;
		}
	for (const [map, live] of [
		[redirects.films, liveFilms],
		[redirects.episodes, liveEpisodes],
	] as const) {
		for (const from of Object.keys(map)) {
			if (live.has(from)) {
				delete map[from];
				continue;
			}
			const seen = new Set([from]);
			let to = map[from];
			while (map[to] && !seen.has(to)) seen.add(to), (to = map[to]);
			if (live.has(to)) map[from] = to;
			else delete map[from];
		}
	}
	return redirects;
}

// Cloudflare's _redirects format; both spellings, since the old link may lack the trailing slash.
export function redirectsFile({ films, episodes }: Redirects) {
	const lines = ['# Generated by scripts/build-data.ts from data/redirects.json. Old URLs → current page.'];
	const add = (from: string, to: string) => lines.push(`${from}/ ${to}/ 301`, `${from} ${to}/ 301`);
	// Retired pages: the Junkies page became a filter on the episodes list; Surprise me was dropped.
	lines.push('/junkies/ /episodes/?junkies 301', '/junkies /episodes/?junkies 301');
	lines.push('/random/ /episodes/ 301', '/random /episodes/ 301');
	for (const [from, to] of Object.entries(films).sort()) add(`/films/${from}`, `/films/${to}`);
	for (const [from, to] of Object.entries(episodes).sort()) add(`/episodes/${from}`, `/episodes/${to}`);
	return lines.join('\n') + '\n';
}
